/**
 * Builds src/data/articleIndex.generated.ts — the lightweight article data the main bundle
 * needs for cards, lists and SEO (titles, summaries, tags, reading-time word counts).
 *
 * The full article bodies (~1 MB of text) stay in src/data/articles/* and only load with the
 * article page, instead of shipping with every page of the site.
 *
 * Run after editing anything in src/data/articles (the build runs it automatically):
 *   npx tsx scripts/buildArticleIndex.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { ARTICLE_RICH_CATALOG } from '../src/data/articleRichCatalog';
import { STATIC_ARTICLE_SOURCES } from '../src/data/staticArticleSources';
import { CORE_ARTICLE_CATALOGS } from '../src/data/articles/coreArticleCatalogs';
import { stripArticleHashtagSection } from '../src/utils/articleContent';
import type { Locale } from '../src/types';

const LOCALES: Locale[] = ['uz', 'ru', 'en'];
const OUTPUT = path.resolve(import.meta.dirname, '../src/data/articleIndex.generated.ts');

function countWords(text: string): number {
  return text.trim().split(/\s+/).filter(Boolean).length;
}

const catalogLight: Record<string, Record<Locale, unknown>> = {};
for (const [key, catalog] of Object.entries(ARTICLE_RICH_CATALOG)) {
  const perLocale = {} as Record<Locale, unknown>;
  for (const locale of LOCALES) {
    const entry = catalog[locale];
    const body = entry?.body?.trim() || '';
    perLocale[locale] = {
      summary: entry?.summary?.trim() || '',
      tags: entry?.tags ?? [],
      bodyLength: body.length,
      bodyWords: countWords(stripArticleHashtagSection(body)),
    };
  }
  catalogLight[key] = perLocale;
}

// Scheduled publishing: an article dated after today (Fergana time) is left out of the build —
// no page, card, sitemap entry or link — until the first build on or after its date. The
// nightly rebuild on the server (scripts/server/nightly_build.sh, 03:30) publishes it that
// morning and pings IndexNow. ARTICLE_PUBLISH_DATE=YYYY-MM-DD overrides "today" for testing.
const publishDate =
  process.env.ARTICLE_PUBLISH_DATE?.trim() ||
  new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Tashkent' }).format(new Date());
const isScheduled = (article: { date?: string }) => Boolean(article.date && article.date > publishDate);
const scheduledArticles = STATIC_ARTICLE_SOURCES.filter(isScheduled);
if (scheduledArticles.length) {
  console.log(
    `[article-index] ${scheduledArticles.length} scheduled after ${publishDate}: ${scheduledArticles.map((a) => `${a.id} (${a.date})`).join(', ')}`,
  );
}

// Cards only — the body comes from the catalog (see resolveArticleBody), so drop the preview.
const staticArticles = STATIC_ARTICLE_SOURCES.filter((article) => !isScheduled(article)).map((article) => ({
  ...article,
  content: { uz: '', ru: '', en: '' },
}));

const source = `// AUTO-GENERATED by scripts/buildArticleIndex.ts — do not edit by hand.
import type { Article, Locale } from '../types';

export interface ArticleCatalogLight {
  summary: string;
  tags: string[];
  /** Length of the full catalog body (decides catalog vs API text, like resolveArticleBody). */
  bodyLength: number;
  /** Words in the body without its hashtag block (for reading time). */
  bodyWords: number;
}

export const ARTICLE_CATALOG_LIGHT: Record<string, Record<Locale, ArticleCatalogLight>> = ${JSON.stringify(catalogLight, null, 2)};

export const STATIC_ARTICLES: Article[] = ${JSON.stringify(staticArticles, null, 2)};
`;

writeFileSync(OUTPUT, source, 'utf8');
console.log(
  `[article-index] ${Object.keys(catalogLight).length} catalog entries, ${staticArticles.length} articles -> ${path.relative(process.cwd(), OUTPUT)} (${Math.round(Buffer.byteLength(source) / 1024)} KB)`,
);

// --- Route keys only (id/slug -> art-* id): what the app shell needs to build article links,
// without shipping the whole index above in the main bundle.
const ROUTE_KEYS_OUTPUT = path.resolve(import.meta.dirname, '../src/data/articleRouteKeys.generated.ts');
const routeKeys: Record<string, string> = {};
for (const article of staticArticles) {
  routeKeys[article.id] = article.id;
  if (article.slug) routeKeys[article.slug] = article.id;
}
writeFileSync(
  ROUTE_KEYS_OUTPUT,
  `// AUTO-GENERATED by scripts/buildArticleIndex.ts — do not edit by hand.
/** Built-in article id or slug -> its public URL key (art-* id). */
export const STATIC_ARTICLE_ROUTE_KEYS: Record<string, string> = ${JSON.stringify(routeKeys, null, 2)};

/** Written but dated after this build: not published yet, so nothing may link to them. */
export const SCHEDULED_ARTICLE_ROUTE_KEYS: string[] = ${JSON.stringify(scheduledArticles.map((a) => a.id))};
`,
  'utf8',
);

// --- Per-article loaders: the article page fetches only its own text, not all ~60 articles.
const LOADERS_OUTPUT = path.resolve(import.meta.dirname, '../src/data/articleCatalogLoaders.generated.ts');
const catalogSource = readFileSync(path.resolve(import.meta.dirname, '../src/data/articleRichCatalog.ts'), 'utf8');
const importedFrom = new Map(
  [...catalogSource.matchAll(/import \{ (\w+) \} from '\.\/articles\/(\w+)';/g)].map((m) => [m[1], m[2]] as const),
);
const loaderLines: string[] = [];
for (const m of catalogSource.slice(catalogSource.indexOf('export const ARTICLE_RICH_CATALOG')).matchAll(/^ {2}'?([\w-]+)'?: (\w+),$/gm)) {
  const [, key, exportName] = m;
  const file = importedFrom.get(exportName);
  if (!file) throw new Error(`[article-index] ${key}: ${exportName} is not imported from ./articles/`);
  loaderLines.push(`  ${JSON.stringify(key)}: () => import('./articles/${file}').then((m) => m.${exportName}),`);
}
for (const key of Object.keys(CORE_ARTICLE_CATALOGS)) {
  loaderLines.push(`  ${JSON.stringify(key)}: () => import('./articles/coreArticleCatalogs').then((m) => m.CORE_ARTICLE_CATALOGS[${JSON.stringify(key)}]),`);
}
const loaderKeys = loaderLines.map((line) => JSON.parse(line.trim().split(':')[0]));
const catalogKeys = Object.keys(ARTICLE_RICH_CATALOG);
if (loaderKeys.length !== catalogKeys.length || catalogKeys.some((key) => !loaderKeys.includes(key))) {
  throw new Error('[article-index] article loaders do not cover ARTICLE_RICH_CATALOG — check articleRichCatalog.ts layout');
}
writeFileSync(
  LOADERS_OUTPUT,
  `// AUTO-GENERATED by scripts/buildArticleIndex.ts — do not edit by hand.
import type { ArticleRichContent, Locale } from '../types';

export type ArticleCatalogEntry = Record<
  Locale,
  { summary?: string; body: string; keyTakeaways: string[]; faq: ArticleRichContent['faq']; tags: string[]; whenToSeeDoctor: string[] }
>;

export const ARTICLE_CATALOG_LOADERS: Record<string, () => Promise<ArticleCatalogEntry>> = {
${loaderLines.join('\n')}
};
`,
  'utf8',
);
console.log(`[article-index] ${loaderLines.length} per-article loaders -> ${path.relative(process.cwd(), LOADERS_OUTPUT)}`);
